#!/bin/sh
# Включает эхоподавитель ECNS v2 (модуль 0x10f1f) по-настоящему в каждом
# разговоре. Включение, пришедшее до начала передачи голоса, модуль
# откладывает и остаётся в обходе, а голосовой тракт стартует ещё при
# наборе номера. Процессор о начале разговора ничего не сообщает, поэтому
# слушаем сигнал ModemManager StateChanged по D-Bus: при переходе звонка в
# MM_CALL_STATE_ACTIVE (4), исходящего или входящего, выключаем и снова
# включаем модуль с паузой. Журнал для этого не годится, он
# запаздывает на секунды.

L=/sys/module/q6voice/parameters/live_set

# Главный параметр ECNS v2 (0x10f1f/0x10e61) из заводской калибровки со
# словом режима 0x0080002c: биты 8 и 9 сняты, шумоподавление мягче.
MODE=$(cat /usr/local/share/q6voice/ecns-10e61.hex)

dbus-monitor --system \
	"type='signal',interface='org.freedesktop.ModemManager1.Call',member='StateChanged'" |
while read -r line; do
	case "$line" in
	*member=StateChanged*)
		read -r old
		read -r new
		[ "$new" = "int32 4" ] || continue
		# Между выключением и включением нужна пауза: если включить
		# следом, процессор обрабатывает оба изменения до ближайшего кадра
		# и модуль остаётся в обходе (звонки 22:25 и 22:26, пауза в
		# миллисекунды, эхо осталось; с паузой 0,5..1 с эхо уходило).
		# Порядок как в удачном ручном опыте: сначала перезапуск модуля,
		# потом слово режима и усиление. Запись параметров до перезапуска
		# (драйвером на гудках) оставляла модуль в обходе.
		(
			sleep 1
			if echo "10f1f 10e00 0" > $L && sleep 1 &&
			   echo "10f1f 10e00 1" > $L && sleep 1 &&
			   echo "10f1f 10e61 hex:$MODE" > $L &&
			   echo "10ef4 10e12 0xC000" > $L; then
				echo "эхоподавитель перезапущен, режим и усиление записаны"
			else
				echo "перезапустить эхоподавитель не удалось"
			fi
		) &
		;;
	esac
done
